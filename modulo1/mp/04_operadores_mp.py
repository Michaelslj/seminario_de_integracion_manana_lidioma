# Sistema de inventario - Operadores matemáticos

precio = 15
cantidad = 20

print("Suma")
print(precio, "+", cantidad, "=", precio + cantidad)

print("Resta")
print(precio, "-", cantidad, "=", precio - cantidad)

print("Multiplicación")
print(precio, "*", cantidad, "=", precio * cantidad)

print("Potencia")
print(precio, "**", 2, "=", precio ** 2)

print("División")
print(precio, "/", cantidad, "=", precio / cantidad)

print("División entera")
print(precio, "//", cantidad, "=", precio // cantidad)

print("Módulo")
print(precio, "%", cantidad, "=", precio % cantidad)

